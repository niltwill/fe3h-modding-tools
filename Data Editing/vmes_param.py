ENTRY_SIZE = 16
STRUCT_FORMAT = "<8H"  # 8 unsigned shorts (2 bytes each), little-endian

FIELDS = [
    "VmesBlockID",
    "BylethGender",
    "DialogueConditional1",
    "DialogueConditional2",
    "CharID",
    "VoiceLineID",
    "PortraitExpression",
    "Animation"
]

FIELD_ENUMS = {
    "BylethGender": enumBylethGender,
    "DialogueConditional1": enumDialogueCondition,
    "DialogueConditional2": enumDialogueCondition,
    "CharID": enumCharacter,
    "PortraitExpression": enumPortraitExpression,
    "Animation": enumAnimation
}

def parse_vmes_param(file_path):
    with open(file_path, "rb") as f:
        data = f.read()

    entries = []
    for i in range(0, len(data), ENTRY_SIZE):
        chunk = data[i:i+ENTRY_SIZE]
        if len(chunk) < ENTRY_SIZE:
            print(f"Warning: Skipping incomplete chunk at {i}")
            continue

        values = struct.unpack(STRUCT_FORMAT, chunk)
        entry = {}
        char_id = values[FIELDS.index("CharID")]

        for field, value in zip(FIELDS, values):
            if value == 0xFFFF:
                entry[field] = "Unset"
            elif field == "PortraitExpression":
                # Look up portrait overrides directly using the integer CharID
                if char_id in characterPortraitOverrides and value in characterPortraitOverrides[char_id]:
                    entry[field] = characterPortraitOverrides[char_id][value]
                else:
                    entry[field] = get_enum_label(enumPortraitExpression, value)
            elif field in FIELD_ENUMS:
                entry[field] = get_enum_label(FIELD_ENUMS[field], value)
            else:
                entry[field] = value

        entries.append(entry)

    # MUST have this return statement, otherwise the function returns None!
    return entries

def save_as_json(entries, output_path):
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(entries, f, indent=2, ensure_ascii=False)

def load_from_json(input_path):
    with open(input_path, "r", encoding="utf-8") as f:
        return json.load(f)

def rebuild_vmes_param(entries, output_path):
    with open(output_path, "wb") as f:
        for entry in entries:
            values = []
            char_id_raw = entry.get("CharID")

            # Resolve CharID to an int for the portrait-override lookup.
            if char_id_raw == "Unset" or char_id_raw is None:
                char_id = None
            elif isinstance(char_id_raw, int):
                char_id = char_id_raw
            else:  # str
                char_id = get_enum_value(enumCharacter, char_id_raw)

            for field in FIELDS:
                raw = entry.get(field, "Unset")
                if raw == "Unset":
                    values.append(0xFFFF)
                elif field == "PortraitExpression":
                    # Check if the character has specific overrides and if the label is one of them
                    found = False
                    if char_id in characterPortraitOverrides:
                        for key, val in characterPortraitOverrides[char_id].items():
                            if val == raw:
                                values.append(key)
                                found = True
                                break

                    # If it wasn't an override (e.g., it's "Neutral_0"), fall back to base enum
                    if not found:
                        values.append(get_enum_value(enumPortraitExpression, raw))

                elif field in FIELD_ENUMS:
                    values.append(get_enum_value(FIELD_ENUMS[field], raw))
                else:
                    values.append(int(raw))
            f.write(struct.pack(STRUCT_FORMAT, *values))

def main():
    if len(sys.argv) < 3:
        print("Usage:")
        print("  python vmes_param.py dump <input.bin/input.dat>")
        print("  python vmes_param.py repack <input.json>")
        print("  [nx\\event\\talk_castle\\text\\JP\\9051-9093.bin]")
        print("  Supports wildcards: *.bin, *.json")
        return

    mode = sys.argv[1].lower()
    input_pattern = sys.argv[2]

    input_files = glob.glob(input_pattern)
    if not input_files:
        print(f"No files matched: {input_pattern}")
        return

    for input_file in input_files:
        try:
            if mode == "dump":
                parsed_data = parse_vmes_param(input_file)
                output_file = os.path.splitext(input_file)[0] + ".json"
                save_as_json(parsed_data, output_file)
                print(f"Dumped: {output_file}")

            elif mode == "repack":
                entries = load_from_json(input_file)
                output_file = os.path.splitext(input_file)[0] + ".bin"
                rebuild_vmes_param(entries, output_file)
                print(f"Rebuilt {len(entries)} entries into {output_file}")

            else:
                print(f"Unknown mode: {mode}")
                print("Use 'dump' or 'repack'.")
                return

        except Exception as e:
            print(f"Error processing {input_file}: {e}")

if __name__ == "__main__":
    main()
